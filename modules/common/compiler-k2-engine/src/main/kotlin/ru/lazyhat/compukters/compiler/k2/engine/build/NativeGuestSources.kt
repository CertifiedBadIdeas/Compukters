package ru.lazyhat.compukters.compiler.k2.engine.build

/** Internal implementation names never replace the public native interface. */
internal fun nativeImplementation(type: String): String =
    "${type.substringBeforeLast('.')}.__CompuktersHandle${type.substringAfterLast('.')}"

/** Expand the analyzed source, preserving user bodies; this output is the actual library compiler input. */
internal fun generateNativeGuestSources(contract: DeclarativeGuestContract): Map<String, String> {
    val boundary = GuestBoundaryTypes(contract)
    val edits = mutableMapOf<String, MutableList<Pair<Int, String>>>()
    val sources = sortedMapOf<String, String>()

    fun insert(
        path: String,
        offset: Int,
        text: String,
    ) {
        edits.getOrPut(path) { mutableListOf() } += offset to text
    }

    contract.nativeInterfaces.forEach { source ->
        val type = contract.types.single { "${it.packageName}.${it.name}" == source.qualifiedName }
        val implementation = nativeImplementation(source.qualifiedName)
        val device = type.deviceId != null
        if (device) {
            insert(
                source.path,
                source.headerEnd,
                "${if (source.hasSupertypes) "," else ":"} compukter.peripheral.Peripheral ",
            )
        }
        val factories =
            buildString {
                type.operations.filter { it.kind == GuestOperationKind.CALL }.forEach { operation ->
                    appendLine(
                        "\n    public fun ${operation.name}Command(${operation.nativeParameters()}): compukter.commands.Command<${operation.result}>",
                    )
                }
            }
        insert(source.path, source.bodyEnd, factories)
        if (!type.resource) {
            val supertype =
                if (device) {
                    "compukter.peripheral.TypedPeripheralProvider<${source.qualifiedName}>(\"${type.deviceId}\")"
                } else {
                    source.qualifiedName
                }
            val body =
                buildString {
                    appendLine()
                    if (device) {
                        appendLine("\n        override fun wrap(handle: Int): ${source.qualifiedName} = $implementation(handle)")
                    } else {
                        type.operations.forEach { appendNativeOperation(contract, boundary, it, "        ") }
                    }
                }
            if (source.companionStart == null) {
                insert(source.path, source.bodyEnd, "\n    public companion object : $supertype {\n$body    }\n")
            } else {
                insert(source.path, source.companionStart, "${if (source.companionHasSupertypes) "," else ":"} $supertype ")
                insert(source.path, requireNotNull(source.companionBodyEnd), body)
            }
        }
        if (device || type.resource) {
            val text =
                buildString {
                    appendLine("/* Generated by Compukters. Do not edit. */")
                    appendLine("package ${type.packageName}")
                    appendLine(
                        "internal value class ${implementation.substringAfterLast('.')}" +
                            "(internal val __compuktersHandle: Int) : ${source.qualifiedName} {",
                    )
                    type.operations.forEach { appendNativeOperation(contract, boundary, it, "    ") }
                    appendLine("}")
                }
            sources[nativeSourcePath(implementation)] = text
        }
    }
    contract.nativeSources.forEach { (path, original) ->
        var expanded = original
        edits[path].orEmpty().sortedByDescending { it.first }.forEach { (offset, text) ->
            expanded = expanded.substring(0, offset) + text + expanded.substring(offset)
        }
        // Library linkage attributes declarations by basename across all installed modules.
        val packageName = path.substringBeforeLast('/').replace('/', '.')
        sources["${path.substringBeforeLast('/')}/$packageName.${path.substringAfterLast('/')}"] = expanded
    }
    contract.boundaryRecords.forEach { (name, record) ->
        val wireType = boundary.wireType(name)
        if (wireType != name && !(record.construction?.factory?.isNotEmpty() == true && record.fields.size == 1)) {
            sources[nativeSourcePath(wireType)] =
                buildString {
                    appendLine("/* Generated by Compukters. Do not edit. */")
                    appendLine("package ${wireType.substringBeforeLast('.')}")
                    appendLine("internal value class ${wireType.substringAfterLast('.')}(")
                    record.fields.forEach { appendLine("    val ${it.name}: ${boundary.wireType(it.type)},") }
                    appendLine(")")
                }
        }
    }
    contract.operations.groupBy { contract.bindingSymbol(it).substringBeforeLast('.') }.forEach { (owner, operations) ->
        sources[nativeSourcePath(owner)] =
            buildString {
                appendLine("/* Generated by Compukters. Do not edit. */")
                appendLine("package ${owner.substringBeforeLast('.')}")
                val results =
                    operations
                        .map { boundary.wireType(it.result) }
                        .filter { '.' in it }
                        .distinct()
                        .sorted()
                require(results.distinctBy { it.substringAfterLast('.') }.size == results.size) { "Ambiguous wire result names in $owner" }
                results.forEach { appendLine("import $it") }
                appendLine("internal object ${owner.substringAfterLast('.')} {")
                operations.sortedBy { it.binding }.forEach { operation ->
                    val parameters = boundary.arguments(operation).joinToString { "${it.name}: ${it.type}" }
                    appendLine(
                        "    external fun ${operation.binding.substringAfterLast(
                            '.',
                        )}($parameters): ${boundary.wireType(operation.result).substringAfterLast('.')}",
                    )
                }
                appendLine("}")
            }
    }
    return sources
}

private fun StringBuilder.appendNativeOperation(
    contract: DeclarativeGuestContract,
    boundary: GuestBoundaryTypes,
    operation: GuestContractOperation,
    indent: String,
) {
    fun validate() {
        operation.parameters.forEach { parameter ->
            parameter.constraints.forEach { constraint ->
                appendLine(
                    "$indent    if (!(${constraint.condition(parameter.name, parameter.type)})) " +
                        "throw IllegalArgumentException(\"Invalid ${parameter.name}\")",
                )
            }
        }
    }
    val symbol = contract.bindingSymbol(operation)
    val arguments = boundary.arguments(operation, "__compuktersHandle")
    appendLine("${indent}public override fun ${operation.name}(${operation.nativeParameters()}): ${operation.result} {")
    validate()
    val call = "$symbol(${arguments.joinToString { it.expression }})"
    if (boundary.wireType(operation.result) == operation.result) {
        appendLine("$indent    return $call")
    } else {
        appendLine("$indent    val reply = $call")
        appendLine("$indent    return ${boundary.decode(operation.result, "reply")}")
    }
    appendLine("$indent}")
    if (operation.kind == GuestOperationKind.CALL) {
        appendLine(
            "${indent}public override fun ${operation.name}Command(${operation.nativeParameters()}): compukter.commands.Command<${operation.result}> {",
        )
        validate()
        val encoded =
            arguments.joinToString { argument ->
                val method = if (argument.type == "ByteArray") "bytes" else argument.type.replaceFirstChar(Char::lowercase)
                "compukter.commands.CommandArgument.$method(${argument.expression})"
            }
        appendLine(
            "$indent    return compukter.commands.createCommand<${operation.result}>(\"${operation.binding}\", listOf($encoded)) { reply ->",
        )
        boundary.decodeCommand(operation.result, "reply").lineSequence().forEach { appendLine("$indent        $it") }
        appendLine("$indent    }")
        appendLine("$indent}")
    }
}

private fun GuestContractOperation.nativeParameters() = parameters.joinToString { "${it.name}: ${it.type}" }

private fun nativeSourcePath(name: String) = "${name.substringBeforeLast('.').replace('.', '/')}/$name.kt"
