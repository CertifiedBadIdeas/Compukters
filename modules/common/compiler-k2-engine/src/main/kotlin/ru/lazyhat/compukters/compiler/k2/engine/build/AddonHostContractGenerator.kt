package ru.lazyhat.compukters.compiler.k2.engine.build

import ru.lazyhat.compukters.addon.api.AddonCapabilityIdentity
import ru.lazyhat.compukters.addon.api.AddonCapabilityValueType
import ru.lazyhat.compukters.addon.api.AddonGuestApiBinding

fun renderAddonHostContract(
    authoring: AddonAuthoringContract,
    resolved: AddonContract,
): String {
    val packageName = "${authoring.addon}.${authoring.module.name}"
    val contractName = "${authoring.module.name.pascalCase()}AddonContract"
    val resourceName = "${authoring.addon}-${authoring.module.name}.cagb"
    val handlers =
        authoring.capabilities.associateWith { capability ->
            "${capability.identity.name.pascalCase()}CapabilityHandler"
        }
    val schemas = resolved.schemas.associateBy { it.identity }
    val bindings = resolved.bindings.groupBy(AddonGuestApiBinding::capability)
    resolved.schemas.flatMap { it.operations }.forEach { operation ->
        require(operation.result in SUPPORTED_HOST_RESULTS) {
            "generated addon hosts cannot complete ${operation.result} results yet"
        }
    }
    return buildString {
        appendLine("/* Generated by Compukters. Do not edit. */")
        appendLine("package $packageName")
        appendLine()
        appendLine("import ru.lazyhat.compukters.addon.api.AddonGuestApiBundle")
        appendLine("import ru.lazyhat.compukters.addon.api.AddonGuestApiBundleCodec")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonCallResult")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonHostHandler")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonPollResult")
        appendLine("import ru.lazyhat.compukters.core.device.runtime.program.ProgramAddonCompletion")
        appendLine("import ru.lazyhat.compukters.core.device.runtime.program.ProgramAddonDispatch")
        appendLine("import ru.lazyhat.compukters.core.device.runtime.program.ProgramAddonHost")
        appendLine("import ru.lazyhat.compukters.core.device.runtime.program.ProgramAddonRequest")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostCapabilitySchema")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostOperationSchema")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostResponse")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostValueType")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.CapabilityIdentity")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.HostFailureKind")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.VmHostRequestIdentity")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.VmValue")
        appendLine()
        handlers.forEach { (capability, handlerName) ->
            appendLine("public interface $handlerName : AddonHostHandler {")
            bindings.getValue(capability.identity).sortedBy(AddonGuestApiBinding::operation).forEach { binding ->
                val operation = schemas.getValue(binding.capability).operations[binding.operation]
                val parameters =
                    operation.arguments.mapIndexed { index, type -> "argument$index: ${type.kotlinType()}" }.joinToString()
                appendLine("    public fun ${binding.callableName}($parameters): AddonCallResult<${operation.result.kotlinType()}>")
                appendLine()
            }
            appendLine("}")
            appendLine()
        }
        appendLine("public object $contractName {")
        appendLine("    public const val GUEST_API_RESOURCE: String = \"/META-INF/compukters/addons/$resourceName\"")
        appendLine()
        appendLine("    public fun guestApi(anchor: Class<*>): AddonGuestApiBundle =")
        appendLine("        AddonGuestApiBundleCodec.decode(")
        appendLine(
            "            checkNotNull(anchor.getResourceAsStream(GUEST_API_RESOURCE)) { \"packaged addon Guest API bundle is missing\" }",
        )
        appendLine("                .use { it.readBytes() },")
        appendLine("        ).also { bundle -> require(bundle.identity.module == \"${authoring.module}\") }")
        appendLine()
        val handlerParameters =
            handlers.entries.joinToString { (capability, handlerName) ->
                "${capability.identity.name}Handler: $handlerName"
            }
        val handlerArguments = handlers.keys.joinToString { "${it.identity.name}Handler" }
        appendLine("    public fun host($handlerParameters): ProgramAddonHost = GeneratedAddonHost($handlerArguments)")
        appendLine("}")
        appendLine()
        appendLine("private class GeneratedAddonHost(")
        handlers.forEach { (capability, handlerName) ->
            appendLine("    private val ${capability.identity.name}Handler: $handlerName,")
        }
        appendLine(") : ProgramAddonHost {")
        appendLine("    private val pending = linkedMapOf<VmHostRequestIdentity, () -> HostResponse?>()")
        appendLine("    override val capabilitySchemas: List<HostCapabilitySchema> = SCHEMAS")
        appendLine()
        appendLine("    override fun dispatch(request: ProgramAddonRequest): ProgramAddonDispatch =")
        appendLine("        when (request.capability) {")
        authoring.capabilities.forEach { capability ->
            appendLine("            ${capability.identity.identityConstant()} -> dispatch${capability.identity.name.pascalCase()}(request)")
        }
        appendLine("            else -> unavailableCapability()")
        appendLine("        }")
        appendLine()
        authoring.capabilities.forEach { capability ->
            appendLine(
                "    private fun dispatch${capability.identity.name.pascalCase()}(request: ProgramAddonRequest): ProgramAddonDispatch =",
            )
            appendLine("        when (request.operation) {")
            bindings.getValue(capability.identity).sortedBy(AddonGuestApiBinding::operation).forEach { binding ->
                val operation = schemas.getValue(binding.capability).operations[binding.operation]
                appendLine("            ${binding.operation} -> {")
                appendLine("                if (request.arguments.size != ${operation.arguments.size}) return malformed()")
                operation.arguments.forEachIndexed { index, type ->
                    appendLine("                val argument$index = ${type.decodeExpression(index)} ?: return malformed()")
                }
                val arguments = operation.arguments.indices.joinToString { "argument$it" }
                appendLine(
                    "                accept(request.identity, ${capability.identity.name}Handler.${binding.callableName}($arguments)) " +
                        "{ ${operation.result.encodeExpression("it")} }",
                )
                appendLine("            }")
            }
            appendLine("            else -> malformed()")
            appendLine("        }")
            appendLine()
        }
        appendLine("    private fun <T> accept(")
        appendLine("        identity: VmHostRequestIdentity,")
        appendLine("        result: AddonCallResult<T>,")
        appendLine("        encode: (T) -> HostResponse,")
        appendLine("    ): ProgramAddonDispatch =")
        appendLine("        when (result) {")
        appendLine("            is AddonCallResult.Completed -> ProgramAddonDispatch.Completed(encode(result.value))")
        appendLine(
            "            is AddonCallResult.Failed -> ProgramAddonDispatch.Completed(HostResponse.Failure(result.kind, result.detail))",
        )
        appendLine("            is AddonCallResult.Pending -> {")
        appendLine("                if (pending.size >= MAXIMUM_PENDING || identity in pending) return pendingUnavailable()")
        appendLine("                pending[identity] = {")
        appendLine("                    when (val completion = result.poll()) {")
        appendLine("                        is AddonPollResult.Completed -> encode(completion.value)")
        appendLine("                        is AddonPollResult.Failed -> HostResponse.Failure(completion.kind, completion.detail)")
        appendLine("                        null -> null")
        appendLine("                    }")
        appendLine("                }")
        appendLine("                ProgramAddonDispatch.Pending")
        appendLine("            }")
        appendLine("        }")
        appendLine()
        appendLine("    override fun poll(maximumCompletions: Int): List<ProgramAddonCompletion> {")
        appendLine("        require(maximumCompletions > 0) { \"maximum addon completions must be positive\" }")
        appendLine("        val completions = mutableListOf<ProgramAddonCompletion>()")
        appendLine("        val iterator = pending.iterator()")
        appendLine("        while (iterator.hasNext() && completions.size < maximumCompletions) {")
        appendLine("            val (identity, poll) = iterator.next()")
        appendLine("            val response = poll() ?: continue")
        appendLine("            iterator.remove()")
        appendLine("            completions += ProgramAddonCompletion(identity, response)")
        appendLine("        }")
        appendLine("        return completions")
        appendLine("    }")
        appendLine()
        appendLine("    override fun reset() {")
        appendLine("        pending.clear()")
        handlers.keys.forEach { capability -> appendLine("        ${capability.identity.name}Handler.reset()") }
        appendLine("    }")
        appendLine()
        appendLine("    override fun close() {")
        appendLine("        pending.clear()")
        handlers.keys
            .toList()
            .asReversed()
            .forEach { capability -> appendLine("        ${capability.identity.name}Handler.close()") }
        appendLine("    }")
        appendLine("}")
        appendLine()
        authoring.capabilities.forEach { capability ->
            appendLine("private val ${capability.identity.identityConstant()}: CapabilityIdentity =")
            appendLine(
                "    CapabilityIdentity(\"${capability.identity.namespace}\", \"${capability.identity.name}\", " +
                    "${capability.identity.abiMajor}, ${capability.identity.abiMinor})",
            )
        }
        appendLine("private val SCHEMAS: List<HostCapabilitySchema> =")
        appendLine("    listOf(")
        resolved.schemas.forEach { schema ->
            appendLine("        HostCapabilitySchema(")
            appendLine("            ${schema.identity.identityConstant()},")
            appendLine("            listOf(")
            schema.operations.forEach { operation ->
                val arguments = operation.arguments.joinToString { "HostValueType.${it.name}" }
                appendLine(
                    "                HostOperationSchema(listOf($arguments), HostValueType.${operation.result.name}, asynchronous = true),",
                )
            }
            appendLine("            ),")
            appendLine("        ),")
        }
        appendLine("    )")
        appendLine("private const val MAXIMUM_PENDING: Int = 64")
        appendLine()
        appendLine("private fun malformed(): ProgramAddonDispatch.Completed =")
        appendLine("    ProgramAddonDispatch.Completed(HostResponse.Failure(HostFailureKind.OTHER, \"Malformed addon request\"))")
        appendLine()
        appendLine("private fun unavailableCapability(): ProgramAddonDispatch.Completed =")
        appendLine(
            "    ProgramAddonDispatch.Completed(HostResponse.Failure(HostFailureKind.UNAVAILABLE, \"Addon capability is unavailable\"))",
        )
        appendLine()
        appendLine("private fun pendingUnavailable(): ProgramAddonDispatch.Completed =")
        appendLine(
            "    ProgramAddonDispatch.Completed(HostResponse.Failure(HostFailureKind.UNAVAILABLE, \"Addon pending request limit was reached\"))",
        )
    }
}

private val SUPPORTED_HOST_RESULTS =
    setOf(
        AddonCapabilityValueType.UNIT,
        AddonCapabilityValueType.I32,
        AddonCapabilityValueType.F32,
        AddonCapabilityValueType.BOOL,
        AddonCapabilityValueType.STRING,
    )

private fun AddonCapabilityValueType.kotlinType(): String =
    when (this) {
        AddonCapabilityValueType.UNIT -> "Unit"
        AddonCapabilityValueType.I32 -> "Int"
        AddonCapabilityValueType.I64 -> "Long"
        AddonCapabilityValueType.F32 -> "Float"
        AddonCapabilityValueType.F64 -> "Double"
        AddonCapabilityValueType.BOOL -> "Boolean"
        AddonCapabilityValueType.CHAR -> "Char"
        AddonCapabilityValueType.STRING -> "String"
    }

private fun AddonCapabilityValueType.decodeExpression(index: Int): String =
    when (this) {
        AddonCapabilityValueType.UNIT -> error("Unit cannot be an addon capability argument")
        AddonCapabilityValueType.I32 -> "(request.arguments[$index] as? VmValue.I32)?.value"
        AddonCapabilityValueType.I64 -> "(request.arguments[$index] as? VmValue.I64)?.value"
        AddonCapabilityValueType.F32 -> "(request.arguments[$index] as? VmValue.F32)?.bits?.let(Float::fromBits)"
        AddonCapabilityValueType.F64 -> "(request.arguments[$index] as? VmValue.F64)?.bits?.let(Double::fromBits)"
        AddonCapabilityValueType.BOOL -> "(request.arguments[$index] as? VmValue.Bool)?.value"
        AddonCapabilityValueType.CHAR -> "(request.arguments[$index] as? VmValue.CharValue)?.value"
        AddonCapabilityValueType.STRING -> "(request.arguments[$index] as? VmValue.StringValue)?.value"
    }

private fun AddonCapabilityValueType.encodeExpression(value: String): String =
    when (this) {
        AddonCapabilityValueType.UNIT -> "HostResponse.UnitSuccess"
        AddonCapabilityValueType.I32 -> "HostResponse.IntSuccess($value)"
        AddonCapabilityValueType.F32 -> "HostResponse.FloatSuccess($value)"
        AddonCapabilityValueType.BOOL -> "HostResponse.BoolSuccess($value)"
        AddonCapabilityValueType.STRING -> "HostResponse.StringSuccess($value)"
        else -> error("generated addon hosts cannot complete $this results yet")
    }

private fun AddonCapabilityIdentity.identityConstant(): String = "${name.uppercase().replace('-', '_')}_IDENTITY"

private fun String.pascalCase(): String =
    split('-', '_').filter(String::isNotEmpty).joinToString("") { part -> part.replaceFirstChar(Char::uppercaseChar) }
