package ru.lazyhat.compukters.compiler.k2.engine.build

import ru.lazyhat.compukters.addon.api.AddonCapabilityIdentity
import ru.lazyhat.compukters.addon.api.AddonCapabilityValueType
import ru.lazyhat.compukters.addon.api.AddonGuestApiBinding
import ru.lazyhat.compukters.addon.api.AddonRecordSchema

fun renderAddonHostContract(
    authoring: AddonAuthoringContract,
    resolved: AddonContract,
    declaration: DeclarativeGuestContract? = null,
): String {
    val packageName = authoring.addon
    val contractName = "${authoring.addon.pascalCase()}AddonContract"
    val resourceName = "${authoring.addon}.cagb"
    val capabilities = resolved.schemas.map { it.identity }
    val handlers =
        capabilities.associateWith { capability ->
            "${capability.name.pascalCase()}CapabilityHandler"
        }
    val schemas = resolved.schemas.associateBy { it.identity }
    val bindings = resolved.bindings.groupBy(AddonGuestApiBinding::capability)
    val declaredOperations = declaration?.operations?.associateBy { declaration.bindingSymbol(it) }
    val boundary = declaration?.let(::GuestBoundaryTypes)

    fun checks(binding: AddonGuestApiBinding): List<String> =
        declaredOperations
            ?.getValue(binding.symbol)
            ?.let { operation ->
                requireNotNull(boundary).arguments(operation).flatMapIndexed { index, argument ->
                    argument.constraints.map { it.condition("argument$index", argument.type) }
                }
            }.orEmpty()
    resolved.schemas.flatMap { it.operations }.forEach { operation ->
        require(operation.result in SUPPORTED_HOST_RESULTS) {
            "generated addon hosts cannot complete ${operation.result} results yet"
        }
    }
    val records = linkedMapOf<String, AddonRecordSchema>()

    fun collect(record: AddonRecordSchema) {
        val previous = records.putIfAbsent(record.typeName, record)
        require(previous == null || previous == record) { "conflicting record schemas for ${record.typeName}" }
        record.fields.mapNotNull { it.record }.forEach(::collect)
    }
    resolved.schemas
        .flatMap { it.operations }
        .mapNotNull { it.resultRecord }
        .forEach(::collect)
    val dtoFields =
        records
            .mapValues { (_, record) ->
                record.fields.map { it.name to (it.record?.typeName ?: it.type.kotlinType()) }
            }.toMutableMap()

    fun collectInput(type: String) {
        val fields = boundary?.fields(type)?.map { it.name to it.type } ?: return
        val previous = dtoFields.putIfAbsent(type, fields)
        require(previous == null || previous == fields) { "conflicting input/output DTO schemas for $type" }
        fields.forEach { collectInput(it.second) }
    }
    declaration?.operations?.forEach { operation -> operation.parameters.forEach { collectInput(it.type) } }
    require(dtoFields.keys.distinctBy { it.substringAfterLast('.') }.size == dtoFields.size) { "generated DTO names must be unique" }

    fun hostParameters(binding: AddonGuestApiBinding): String {
        val declared = declaredOperations?.getValue(binding.symbol)
        if (declared == null) {
            return schemas
                .getValue(binding.capability)
                .operations[binding.operation]
                .arguments
                .mapIndexed {
                    index,
                    type,
                    ->
                    "argument$index: ${type.kotlinType()}"
                }.joinToString()
        }
        val types = (if (declared.device) listOf("Int") else emptyList()) + declared.parameters.map { it.type.substringAfterLast('.') }
        return types.mapIndexed { index, type -> "argument$index: $type" }.joinToString()
    }
    return buildString {
        appendLine("/* Generated by Compukters. Do not edit. */")
        appendLine("package $packageName")
        appendLine()
        appendLine("import ru.lazyhat.compukters.addon.api.AddonGuestApiBundle")
        appendLine("import ru.lazyhat.compukters.addon.api.AddonGuestApiBundleCodec")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonCallResult")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonCheckpointCodec")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonHostHandler")
        appendLine("import ru.lazyhat.compukters.api.addon.AddonPollResult")
        appendLine("import ru.lazyhat.compukters.api.addon.ProgramAddonCompletion")
        appendLine("import ru.lazyhat.compukters.api.addon.ProgramAddonDispatch")
        appendLine("import ru.lazyhat.compukters.api.addon.ProgramAddonHost")
        appendLine("import ru.lazyhat.compukters.api.addon.ProgramAddonRequest")
        appendLine("import ru.lazyhat.compukters.api.commands.ProgramCommandBinding")
        appendLine("import ru.lazyhat.compukters.api.commands.ProgramCommandProvider")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostCapabilitySchema")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostOperationSchema")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostResponse")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostValueType")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.CapabilityIdentity")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.HostFailureKind")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.VmHostRequestIdentity")
        appendLine("import ru.lazyhat.compukters.lang.runtime.vm.VmValue")
        appendLine()
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostRecordSchema")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostRecordField")
        appendLine("import ru.lazyhat.compukters.lang.runtime.capability.HostRecordValue")
        appendLine()
        dtoFields.forEach { (type, fields) ->
            val name = type.substringAfterLast('.')
            if (declaration != null && type in guestMathematicalTypes) {
                appendLine("public typealias $name = ru.lazyhat.compukters.api.contracts.types.$name")
            } else {
                appendLine("public data class $name(")
                fields.forEach { (name, fieldType) ->
                    appendLine("    public val $name: ${fieldType.substringAfterLast('.')},")
                }
                appendLine(")")
            }
            appendLine()
        }
        handlers.forEach { (capability, handlerName) ->
            appendLine("public interface $handlerName : AddonHostHandler {")
            bindings.getValue(capability).sortedBy(AddonGuestApiBinding::operation).forEach { binding ->
                val operation = schemas.getValue(binding.capability).operations[binding.operation]
                val parameters = hostParameters(binding)
                appendLine(
                    "    public fun ${binding.callableName}($parameters): AddonCallResult<${operation.resultRecord?.simpleName() ?: operation.result.kotlinType()}>",
                )
                appendLine()
            }
            appendLine("}")
            appendLine()
        }
        appendLine("public object $contractName {")
        appendLine("    public const val GUEST_API_RESOURCE: String = \"/META-INF/compukters/addons/$resourceName\"")
        appendLine()
        appendLine("    public fun guestApi(anchor: Class<*>): AddonGuestApiBundle =")
        appendLine("        AddonGuestApiBundleCodec.decode(")
        appendLine(
            "            checkNotNull(anchor.getResourceAsStream(GUEST_API_RESOURCE)) { \"packaged addon Guest API bundle is missing\" }",
        )
        appendLine("                .use { it.readBytes() },")
        appendLine("        ).also { bundle -> require(bundle.identity.id == \"${authoring.addon}\") }")
        appendLine()
        val handlerParameters =
            handlers.entries.joinToString { (capability, handlerName) ->
                "${capability.name}Handler: $handlerName"
            }
        val handlerArguments = handlers.keys.joinToString { "${it.name}Handler" }
        appendLine("    public fun host($handlerParameters): ProgramAddonHost = GeneratedAddonHost($handlerArguments)")
        appendLine("}")
        appendLine()
        appendLine("private class GeneratedAddonHost(")
        handlers.forEach { (capability, handlerName) ->
            appendLine("    private val ${capability.name}Handler: $handlerName,")
        }
        appendLine(") : ProgramAddonHost, ProgramCommandProvider {")
        appendLine("    private val pending = linkedMapOf<VmHostRequestIdentity, () -> HostResponse?>()")
        appendLine("    override val capabilitySchemas: List<HostCapabilitySchema> = SCHEMAS")
        appendLine()
        appendLine("    override val commandBindings: List<ProgramCommandBinding> = buildList {")
        capabilities.forEach { capability ->
            bindings.getValue(capability).sortedBy(AddonGuestApiBinding::operation).forEach { binding ->
                val operation = schemas.getValue(binding.capability).operations[binding.operation]
                if (operation.result != AddonCapabilityValueType.UNIT) return@forEach
                if (declaredOperations != null &&
                    declaredOperations.getValue(binding.symbol).kind != GuestOperationKind.COMMAND
                ) {
                    return@forEach
                }
                val types = operation.arguments.joinToString { "HostValueType.${it.name}" }
                appendLine(
                    if (declaration ==
                        null
                    ) {
                        "        if (${capability.name}Handler.batchCommands.contains(\"${binding.callableName}\")) {"
                    } else {
                        "        run {"
                    },
                )
                appendLine(
                    "            add(ProgramCommandBinding(\"${binding.symbol}\", ${capability.identityConstant()}, ${binding.operation}, listOf($types), command@ { arguments ->",
                )
                appendLine("                if (arguments.size != ${operation.arguments.size}) return@command invalidCommand()")
                operation.arguments.forEachIndexed { index, type ->
                    val decode = type.decodeExpression(index).replace("request.arguments", "arguments")
                    appendLine("                val argument$index = $decode ?: return@command invalidCommand()")
                }
                checks(binding).forEach { appendLine("                if (!($it)) return@command invalidCommand()") }
                val arguments =
                    hostArguments(
                        declaredOperations?.getValue(binding.symbol),
                        boundary,
                        operation.arguments.size,
                        "return@command invalidCommand()",
                        "                ",
                    )
                appendLine("                acceptCommand(${capability.name}Handler.${binding.callableName}($arguments))")
                appendLine("            }))")
                appendLine("        }")
            }
        }
        appendLine("    }")
        appendLine()
        if (declaration == null) {
            appendLine("    init {")
            capabilities.forEach { capability ->
                val names =
                    bindings
                        .getValue(capability)
                        .filter { schemas.getValue(it.capability).operations[it.operation].result == AddonCapabilityValueType.UNIT }
                        .joinToString { "\"${it.callableName}\"" }
                appendLine(
                    "        require(${capability.name}Handler.batchCommands.all { it in setOf<String>($names) }) { \"Batch commands must name immediate Unit methods\" }",
                )
            }
            appendLine("    }")
            appendLine()
        }
        appendLine(
            "    private fun invalidCommand(): HostResponse = HostResponse.Failure(HostFailureKind.OTHER, \"Malformed command arguments\")",
        )
        appendLine()
        appendLine("    private fun acceptCommand(result: AddonCallResult<Unit>): HostResponse = when (result) {")
        appendLine("        is AddonCallResult.Completed -> HostResponse.UnitSuccess")
        appendLine("        is AddonCallResult.Failed -> HostResponse.Failure(result.kind, result.detail)")
        appendLine(
            "        is AddonCallResult.Pending -> HostResponse.Failure(HostFailureKind.OTHER, \"Command handler attempted to wait\")",
        )
        appendLine("    }")
        appendLine()
        appendLine("    override fun dispatch(request: ProgramAddonRequest): ProgramAddonDispatch =")
        appendLine("        when (request.capability) {")
        capabilities.forEach { capability ->
            appendLine("            ${capability.identityConstant()} -> dispatch${capability.name.pascalCase()}(request)")
        }
        appendLine("            else -> unavailableCapability()")
        appendLine("        }")
        appendLine()
        capabilities.forEach { capability ->
            appendLine(
                "    private fun dispatch${capability.name.pascalCase()}(request: ProgramAddonRequest): ProgramAddonDispatch =",
            )
            appendLine("        when (request.operation) {")
            bindings.getValue(capability).sortedBy(AddonGuestApiBinding::operation).forEach { binding ->
                val operation = schemas.getValue(binding.capability).operations[binding.operation]
                appendLine("            ${binding.operation} -> {")
                appendLine("                if (request.arguments.size != ${operation.arguments.size}) return malformed()")
                operation.arguments.forEachIndexed { index, type ->
                    appendLine("                val argument$index = ${type.decodeExpression(index)} ?: return malformed()")
                }
                checks(binding).forEach { appendLine("                if (!($it)) return malformed()") }
                val arguments =
                    hostArguments(
                        declaredOperations?.getValue(binding.symbol),
                        boundary,
                        operation.arguments.size,
                        "return malformed()",
                        "                ",
                    )
                val allowPending = declaredOperations?.getValue(binding.symbol)?.let { it.kind == GuestOperationKind.WAIT } ?: true
                appendLine(
                    "                accept(request.identity, " +
                        "${capability.name}Handler.${binding.callableName}($arguments), $allowPending) " +
                        "{ ${operation.resultRecord?.let { "encode${it.simpleName()}(it)" } ?: operation.result.encodeExpression("it")} }",
                )
                appendLine("            }")
            }
            appendLine("            else -> malformed()")
            appendLine("        }")
            appendLine()
        }
        appendLine("    private fun <T> accept(")
        appendLine("        identity: VmHostRequestIdentity,")
        appendLine("        result: AddonCallResult<T>,")
        appendLine("        allowPending: Boolean,")
        appendLine("        encode: (T) -> HostResponse,")
        appendLine("    ): ProgramAddonDispatch =")
        appendLine("        when (result) {")
        appendLine("            is AddonCallResult.Completed -> ProgramAddonDispatch.Completed(encode(result.value))")
        appendLine(
            "            is AddonCallResult.Failed -> ProgramAddonDispatch.Completed(HostResponse.Failure(result.kind, result.detail))",
        )
        appendLine("            is AddonCallResult.Pending -> {")
        appendLine(
            "                if (!allowPending) return ProgramAddonDispatch.Completed(" +
                "HostResponse.Failure(HostFailureKind.OTHER, \"Immediate addon method attempted to wait\"))",
        )
        appendLine("                if (pending.size >= MAXIMUM_PENDING || identity in pending) return pendingUnavailable()")
        appendLine("                pending[identity] = {")
        appendLine("                    when (val completion = result.poll()) {")
        appendLine("                        is AddonPollResult.Completed -> encode(completion.value)")
        appendLine("                        is AddonPollResult.Failed -> HostResponse.Failure(completion.kind, completion.detail)")
        appendLine("                        null -> null")
        appendLine("                    }")
        appendLine("                }")
        appendLine("                ProgramAddonDispatch.Pending")
        appendLine("            }")
        appendLine("        }")
        appendLine()
        appendLine("    override fun poll(maximumCompletions: Int): List<ProgramAddonCompletion> {")
        appendLine("        require(maximumCompletions > 0) { \"maximum addon completions must be positive\" }")
        appendLine("        val completions = mutableListOf<ProgramAddonCompletion>()")
        appendLine("        val iterator = pending.iterator()")
        appendLine("        while (iterator.hasNext() && completions.size < maximumCompletions) {")
        appendLine("            val (identity, poll) = iterator.next()")
        appendLine("            val response = poll() ?: continue")
        appendLine("            iterator.remove()")
        appendLine("            completions += ProgramAddonCompletion(identity, response)")
        appendLine("        }")
        appendLine("        return completions")
        appendLine("    }")
        appendLine()
        appendLine("    override fun checkpoint(): ByteArray = AddonCheckpointCodec.encode(listOf(")
        handlers.keys.forEach { capability -> appendLine("        ${capability.name}Handler.checkpoint(),") }
        appendLine("    ))")
        appendLine()
        appendLine("    override fun restoreCheckpoint(state: ByteArray) {")
        appendLine("        val parts = AddonCheckpointCodec.decode(state, ${handlers.size})")
        handlers.keys.forEachIndexed {
            index,
            capability,
            ->
            appendLine("        ${capability.name}Handler.restoreCheckpoint(parts[$index])")
        }
        appendLine("    }")
        appendLine()
        appendLine("    override fun reset() {")
        appendLine("        pending.clear()")
        handlers.keys.forEach { capability -> appendLine("        ${capability.name}Handler.reset()") }
        appendLine("    }")
        appendLine()
        appendLine("    override fun close() {")
        appendLine("        pending.clear()")
        handlers.keys
            .toList()
            .asReversed()
            .forEach { capability -> appendLine("        ${capability.name}Handler.close()") }
        appendLine("    }")
        appendLine("}")
        appendLine()
        capabilities.forEach { capability ->
            appendLine("private val ${capability.identityConstant()}: CapabilityIdentity =")
            appendLine(
                "    CapabilityIdentity(\"${capability.namespace}\", \"${capability.name}\", " +
                    "${capability.abiMajor}, ${capability.abiMinor})",
            )
        }
        records.values.forEach { record ->
            appendLine("private val ${record.schemaConstant()}: HostRecordSchema = ${record.schemaExpression()}")
            appendLine()
            appendLine("private fun encode${record.simpleName()}(value: ${record.simpleName()}): HostResponse.RecordSuccess =")
            appendLine("    HostResponse.RecordSuccess(HostRecordValue(${record.schemaConstant()}, listOf(")
            record.fields.forEach { field ->
                val expression =
                    field.record?.let { "encode${it.simpleName()}(value.${field.name})" }
                        ?: field.type.encodeExpression("value.${field.name}")
                appendLine("        $expression,")
            }
            appendLine("    )))")
            appendLine()
        }
        appendLine("private val SCHEMAS: List<HostCapabilitySchema> =")
        appendLine("    listOf(")
        resolved.schemas.forEach { schema ->
            appendLine("        HostCapabilitySchema(")
            appendLine("            ${schema.identity.identityConstant()},")
            appendLine("            listOf(")
            schema.operations.forEach { operation ->
                val arguments = operation.arguments.joinToString { "HostValueType.${it.name}" }
                val resultRecord = operation.resultRecord?.let { ", resultRecord = ${it.schemaConstant()}" }.orEmpty()
                appendLine(
                    "                HostOperationSchema(listOf($arguments), HostValueType.${operation.result.name}, " +
                        "asynchronous = true$resultRecord),",
                )
            }
            appendLine("            ),")
            appendLine("        ),")
        }
        appendLine("    )")
        appendLine("private const val MAXIMUM_PENDING: Int = 64")
        appendLine()
        appendLine("private fun malformed(): ProgramAddonDispatch.Completed =")
        appendLine("    ProgramAddonDispatch.Completed(HostResponse.Failure(HostFailureKind.OTHER, \"Malformed addon request\"))")
        appendLine()
        appendLine("private fun unavailableCapability(): ProgramAddonDispatch.Completed =")
        appendLine(
            "    ProgramAddonDispatch.Completed(HostResponse.Failure(HostFailureKind.UNAVAILABLE, \"Addon capability is unavailable\"))",
        )
        appendLine()
        appendLine("private fun pendingUnavailable(): ProgramAddonDispatch.Completed =")
        appendLine(
            "    ProgramAddonDispatch.Completed(HostResponse.Failure(HostFailureKind.UNAVAILABLE, \"Addon pending request limit was reached\"))",
        )
    }
}

/** Reconstruct public values only after all wire arguments and declared constraints have been checked. */
private fun StringBuilder.hostArguments(
    operation: GuestContractOperation?,
    boundary: GuestBoundaryTypes?,
    wireCount: Int,
    invalid: String,
    indent: String,
): String {
    if (operation == null) return (0 until wireCount).joinToString { "argument$it" }
    val types = requireNotNull(boundary)
    var cursor = if (operation.device) 1 else 0

    fun construct(type: String): String {
        val fields = types.fields(type) ?: return "argument${cursor++}"
        val values = fields.map { construct(it.type) }
        val name = type.substringAfterLast('.')
        return if (type == "kotlin.math.Rotation3d" ||
            type == "kotlin.math.Rotation3f"
        ) {
            "$name.fromQuaternion(${values.single()})"
        } else {
            "$name(${values.joinToString()})"
        }
    }

    fun checked(type: String): Boolean =
        type == "kotlin.math.Rotation3d" || type == "kotlin.math.Rotation3f" || types.fields(type).orEmpty().any { checked(it.type) }
    val arguments = if (operation.device) mutableListOf("argument0") else mutableListOf()
    operation.parameters.forEachIndexed { index, parameter ->
        val expression = construct(parameter.type)
        if (checked(parameter.type)) {
            val value = "typedArgument$index"
            appendLine("${indent}val $value = try { $expression } catch (failure: IllegalArgumentException) { $invalid }")
            arguments += value
        } else {
            arguments += expression
        }
    }
    check(cursor == wireCount) { "host argument reconstruction does not match the wire schema" }
    return arguments.joinToString()
}

private val SUPPORTED_HOST_RESULTS =
    setOf(
        AddonCapabilityValueType.UNIT,
        AddonCapabilityValueType.I32,
        AddonCapabilityValueType.I64,
        AddonCapabilityValueType.F64,
        AddonCapabilityValueType.CHAR,
        AddonCapabilityValueType.F32,
        AddonCapabilityValueType.BOOL,
        AddonCapabilityValueType.STRING,
        AddonCapabilityValueType.RECORD,
        AddonCapabilityValueType.BYTE_ARRAY,
    )

private fun AddonCapabilityValueType.kotlinType(): String =
    when (this) {
        AddonCapabilityValueType.UNIT -> "Unit"
        AddonCapabilityValueType.I32 -> "Int"
        AddonCapabilityValueType.I64 -> "Long"
        AddonCapabilityValueType.F32 -> "Float"
        AddonCapabilityValueType.F64 -> "Double"
        AddonCapabilityValueType.BOOL -> "Boolean"
        AddonCapabilityValueType.CHAR -> "Char"
        AddonCapabilityValueType.STRING -> "String"
        AddonCapabilityValueType.BYTE_ARRAY -> "ByteArray"
        AddonCapabilityValueType.RECORD -> error("record types require a schema")
    }

private fun AddonCapabilityValueType.decodeExpression(index: Int): String =
    when (this) {
        AddonCapabilityValueType.UNIT -> error("Unit cannot be an addon capability argument")
        AddonCapabilityValueType.RECORD -> error("records cannot be addon capability arguments")
        AddonCapabilityValueType.I32 -> "(request.arguments[$index] as? VmValue.I32)?.value"
        AddonCapabilityValueType.I64 -> "(request.arguments[$index] as? VmValue.I64)?.value"
        AddonCapabilityValueType.F32 -> "(request.arguments[$index] as? VmValue.F32)?.bits?.let(Float::fromBits)"
        AddonCapabilityValueType.F64 -> "(request.arguments[$index] as? VmValue.F64)?.bits?.let(Double::fromBits)"
        AddonCapabilityValueType.BOOL -> "(request.arguments[$index] as? VmValue.Bool)?.value"
        AddonCapabilityValueType.CHAR -> "(request.arguments[$index] as? VmValue.CharValue)?.value"
        AddonCapabilityValueType.STRING -> "(request.arguments[$index] as? VmValue.StringValue)?.value"
        AddonCapabilityValueType.BYTE_ARRAY -> "(request.arguments[$index] as? VmValue.ByteArrayValue)?.value"
    }

private fun AddonCapabilityValueType.encodeExpression(value: String): String =
    when (this) {
        AddonCapabilityValueType.RECORD -> error("record responses require a schema")
        AddonCapabilityValueType.UNIT -> "HostResponse.UnitSuccess"
        AddonCapabilityValueType.I32 -> "HostResponse.IntSuccess($value)"
        AddonCapabilityValueType.I64 -> "HostResponse.LongSuccess($value)"
        AddonCapabilityValueType.F64 -> "HostResponse.DoubleSuccess($value)"
        AddonCapabilityValueType.CHAR -> "HostResponse.CharSuccess($value)"
        AddonCapabilityValueType.F32 -> "HostResponse.FloatSuccess($value)"
        AddonCapabilityValueType.BOOL -> "HostResponse.BoolSuccess($value)"
        AddonCapabilityValueType.STRING -> "HostResponse.StringSuccess($value)"
        AddonCapabilityValueType.BYTE_ARRAY -> "HostResponse.ByteArraySuccess($value)"
    }

private fun AddonCapabilityIdentity.identityConstant(): String = "${name.uppercase().replace('-', '_')}_IDENTITY"

private fun String.pascalCase(): String =
    split('-', '_').filter(String::isNotEmpty).joinToString("") { part -> part.replaceFirstChar(Char::uppercaseChar) }

private fun AddonRecordSchema.simpleName(): String = typeName.substringAfterLast('.')

private fun AddonRecordSchema.schemaConstant(): String = "RECORD_${simpleName().uppercase()}"

private fun AddonRecordSchema.schemaExpression(): String =
    "HostRecordSchema(\"$typeName\", listOf(" +
        fields.joinToString { field ->
            "HostRecordField(\"${field.name}\", HostValueType.${field.type.name}" +
                (field.record?.let { ", ${it.schemaExpression()}" } ?: "") + ")"
        } + "))"
