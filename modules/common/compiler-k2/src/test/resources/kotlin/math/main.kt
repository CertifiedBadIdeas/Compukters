import kotlin.math.*

fun near(actual: Double, expected: Double) {
    check(abs(actual - expected) <= max(1.0, abs(expected)) * 1e-12) { "Expected $expected, got $actual" }
}

fun near(actual: Float, expected: Float) {
    check(abs(actual - expected) <= max(1.0f, abs(expected)) * 2e-6f) { "Expected $expected, got $actual" }
}

class Order(var value: Int)

fun operand(order: Order, value: Double): Double {
    order.value = order.value * 10 + value.toInt()
    return value
}

