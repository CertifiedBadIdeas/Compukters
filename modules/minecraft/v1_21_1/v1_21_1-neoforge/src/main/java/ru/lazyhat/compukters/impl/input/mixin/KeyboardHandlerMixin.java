package ru.lazyhat.compukters.impl.input.mixin;

import net.minecraft.client.KeyboardHandler;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import ru.lazyhat.compukters.impl.input.KeyboardInputClient;

@Mixin(KeyboardHandler.class)
public abstract class KeyboardHandlerMixin {
    @Inject(method = "keyPress", at = @At("HEAD"), cancellable = true)
    private void compukters$capture(long window, int key, int scanCode, int action, int modifiers, CallbackInfo callback) {
        if (KeyboardInputClient.consumeKey(key, action)) callback.cancel();
    }
}
